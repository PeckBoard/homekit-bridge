#!/usr/bin/env node
// Regenerates src/hapNames.ts from hap-nodejs's service/characteristic
// definitions (the canonical HAP names: Lightbulb, TemperatureSensor,
// CurrentHeatingCoolingState, ...). Dev-only: hap-nodejs is a devDependency
// and never reaches the bundle.
//
//   node scripts/gen-hap-names.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const hap = require("hap-nodejs");

function words(name) {
  return name
    .replace(/_/g, " ")
    .replace(/([a-z])v(\d)/g, "$1 V$2") // Fanv2 -> Fan V2
    .replace(/([a-z\d])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .trim()
    .split(/\s+/);
}

function table(ns) {
  const out = {};
  for (const key of Object.getOwnPropertyNames(ns).sort()) {
    const cls = ns[key];
    if (typeof cls !== "function" || typeof cls.UUID !== "string") continue;
    // Deprecated aliases point at a class with a different name; keep the
    // canonical one.
    if (cls.name !== key && out[cls.UUID]) continue;
    const w = words(key);
    out[cls.UUID] = [w.join("-").toLowerCase(), w.join(" ")];
  }
  return out;
}

const services = table(hap.Service);
const characteristics = table(hap.Characteristic);
const fmt = (o) =>
  Object.entries(o)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([u, [k, d]]) => `  "${u}": [${JSON.stringify(k)}, ${JSON.stringify(d)}],`)
    .join("\n");

const src = `// GENERATED by scripts/gen-hap-names.mjs from hap-nodejs ${hap.HAPLibraryVersion()}.
// Do not edit by hand. UUID -> [kebab-case name, display name].

export const SERVICE_NAMES: Record<string, [string, string]> = {
${fmt(services)}
};

export const CHARACTERISTIC_NAMES: Record<string, [string, string]> = {
${fmt(characteristics)}
};
`;
const target = new URL("../src/hapNames.ts", import.meta.url);
writeFileSync(target, src);
console.log(
  `wrote ${target.pathname}: ${Object.keys(services).length} services, ${Object.keys(characteristics).length} characteristics`,
);
